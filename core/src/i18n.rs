//! Interface language. Spanish is the source text; English is used for any other locale.
//! FLUXDECK_LANG=es|en overrides the locale.
use std::sync::OnceLock;

static ENGLISH: OnceLock<bool> = OnceLock::new();

pub fn english() -> bool {
    *ENGLISH.get_or_init(|| {
        let lang = ["FLUXDECK_LANG", "LANGUAGE", "LC_ALL", "LC_MESSAGES", "LANG"]
            .iter()
            .find_map(|v| std::env::var(v).ok().filter(|s| !s.is_empty()))
            .unwrap_or_default();
        !lang.starts_with("es")
    })
}

/// Fixes the language from the config ("es" or "en"); call before the first translation.
pub fn init(language: &str) {
    if matches!(language, "es" | "en") {
        let _ = ENGLISH.set(language == "en");
    }
}

/// Translates a Spanish interface string.
pub fn t(s: &'static str) -> &'static str {
    if !english() {
        return s;
    }
    EN.iter().find(|(es, _)| *es == s).map_or(s, |(_, en)| en)
}

/// Translates, then fills each `{}` with the next argument.
pub fn tf(s: &'static str, args: &[&str]) -> String {
    let mut out = t(s).to_string();
    for a in args {
        out = out.replacen("{}", a, 1);
    }
    out
}

pub fn has(s: &str) -> bool {
    EN.iter().any(|(es, _)| *es == s)
}

